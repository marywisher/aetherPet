-- ================================================================
-- 003_add_pets_offline_start.sql
-- 功能：pets 表新增 offline_start_ts —— 最近一次离线补算窗口的起点
-- 用途：作为「你不在的时候发生的新事件」分界锚点持久化：
--       补算发生时更新为窗口起点；频繁刷新（无补算窗口）时保留旧值，
--       保证首页/时间线的新旧分组与分割线跨会话稳定（不随刷新消失）。
-- 验收对齐：requirements.md §6 #4/#5 补算/事件流（新旧事件可分辨）
-- 注意：DDL 非事务；一次性应用
-- ================================================================

ALTER TABLE pets
  ADD COLUMN offline_start_ts BIGINT UNSIGNED NULL AFTER last_activity_ts;